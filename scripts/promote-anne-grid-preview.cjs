const fs = require("fs");
const vm = require("vm");
const crypto = require("crypto");

const PREVIEW = "src/catalog-anne-grid-preview.js";
const SUMMARY = "docs/audits/anne-grid-summary.json";

function loadCatalog(path) {
  const context = { window: {} };
  vm.createContext(context);
  vm.runInContext(fs.readFileSync(path, "utf8"), context);
  return JSON.parse(JSON.stringify(context.window.HEXIVA_CATALOG));
}

function assertEmpty(summary, key) {
  if (!Array.isArray(summary[key]) || summary[key].length !== 0) {
    throw new Error(`Cannot promote: ${key} is not empty`);
  }
}

function replaceExactly(text, before, after, label) {
  const matches = text.split(before).length - 1;
  if (matches !== 1)
    throw new Error(`Cannot promote: expected exactly one ${label}, found ${matches}`);
  return text.replace(before, after);
}

function main() {
  if (!fs.existsSync(PREVIEW) || !fs.existsSync(SUMMARY))
    throw new Error(
      "Cannot promote: build and audit the anne-grid preview first.",
    );

  const previewSource = fs.readFileSync(PREVIEW, "utf8");
  const previewSha256 = crypto
    .createHash("sha256")
    .update(previewSource)
    .digest("hex");
  const catalog = loadCatalog(PREVIEW);
  const summary = JSON.parse(fs.readFileSync(SUMMARY, "utf8"));

  if (!summary.catalogSha256 || summary.catalogSha256 !== previewSha256)
    throw new Error(
      "Cannot promote: preview bytes do not match the audited catalog hash.",
    );

  if (catalog.length !== 1250) throw new Error("Cannot promote: preview is not 1250 levels");
  if (summary.auditedLevels !== 1250)
    throw new Error("Cannot promote: audit did not cover all 1250 levels");
  if (summary.anneGridLevels !== 250)
    throw new Error("Cannot promote: audit did not find exactly 250 anne-grid levels");

  for (const key of [
    "qualityViolations",
    "solvabilityStalls",
    "visualViolations",
    "nearFootprintRepeatsWithin8",
    "familyRepeatsWithin8",
    "nonfunctionalMechanisms",
    "openingOutcomeUnknowns",
    "anneGridCadenceViolations",
  ])
    assertEmpty(summary, key);

  const finalSource = previewSource.replace(
    /^\/\/ Preview generated[^\n]*\n/,
    "// Generated by audited anne-grid promotion; do not hand-edit.\n",
  );
  fs.writeFileSync("src/catalog.js", finalSource);

  let html = fs.readFileSync("index.html", "utf8");
  html = replaceExactly(
    html,
    "const LEVEL_CATALOG_SIZE = 1000;",
    "const LEVEL_CATALOG_SIZE = 1250;",
    "LEVEL_CATALOG_SIZE",
  );
  html = replaceExactly(
    html,
    "<span>1000+ BÖLÜM</span>",
    "<span>1250 BÖLÜM</span>",
    "menu level-count label",
  );
  fs.writeFileSync("index.html", html);

  let offline = fs.readFileSync("scripts/build-offline.mjs", "utf8");
  offline = replaceExactly(
    offline,
    "catalogContext.window.HEXIVA_CATALOG?.length !== 1000",
    "catalogContext.window.HEXIVA_CATALOG?.length !== 1250",
    "offline catalog count",
  );
  offline = replaceExactly(
    offline,
    '"Release requires 1000 ordered, quality-accepted catalog entries"',
    '"Release requires 1250 ordered, quality-accepted catalog entries"',
    "offline release message",
  );
  fs.writeFileSync("scripts/build-offline.mjs", offline);

  let runtimeTest = fs.readFileSync("tests/runtime-scene.test.cjs", "utf8");
  runtimeTest = replaceExactly(
    runtimeTest,
    'test("all 1000 catalog boards construct and clean up with real Three.js geometry (renderer stub)",',
    'test("all 1250 catalog boards construct and clean up with real Three.js geometry (renderer stub)",',
    "runtime scene test title",
  );
  runtimeTest = replaceExactly(
    runtimeTest,
    "assert.equal(c.window.HEXIVA_CATALOG.length, 1000);",
    "assert.equal(c.window.HEXIVA_CATALOG.length, 1250);",
    "runtime scene catalog assertion",
  );
  fs.writeFileSync("tests/runtime-scene.test.cjs", runtimeTest);

  console.log(
    "Promoted audited anne-grid preview: 1250 levels (1000 preserved normal + 250 special).",
  );
}

if (require.main === module) main();
